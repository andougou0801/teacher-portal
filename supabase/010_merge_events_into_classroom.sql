-- ============================================================================
-- 「学校行事・年間行事」を「学級経営」にまとめる（2026-11-03、運営者の指示）
--
-- これを実行すると
--   1. 行事の記事（section = 'event'）が、学級経営の記事になります
--      （「4月」などの時期タグはそのまま残り、カードの先頭に出ます）
--   2. トップページのカテゴリーが10個から9個になり、
--      「学級経営・子ども対応」が「学級経営」という名前になります
--   3. /classroom ページの見出しと紹介文、テーマ一覧が、行事もふくむ形になります
--
-- /events を開いた人は /classroom へ自動で移ります（コード側で設定ずみ）。
-- Supabase の SQL Editor に貼り付けて実行してください。何度実行しても安全です。
-- ============================================================================

-- 1. 行事の記事を、学級経営の記事にする
update articles
set section = 'classroom',
    updated_at = now()
where section = 'event';

-- 2. トップページのカテゴリーをまとめる
update site_categories
set label = '学級経営',
    description = '学級開き・トラブル対応・保護者対応から、運動会や学習発表会などの行事まで。困った場面と時期から探せるページ。',
    updated_at = now()
where slug = 'classroom';

delete from site_categories where slug = 'events';

-- 3. /classroom ページの見出し・紹介文・テーマ一覧
update page_texts
set heading = '学級経営',
    lead = '日々の学級経営から年間の行事まで、教員が困りやすい場面と時期から探せるページを目指しています。',
    topics = array[
      '班活動','係活動','掃除','給食','褒め方','叱り方',
      '子ども同士のトラブル','授業中の私語','個人懇談',
      '授業参観','遠足','運動会','学習発表会','修学旅行',
      '学期末','学級じまい'
    ],
    updated_at = now()
where slug = 'classroom';

// かくにんモード（おとな用の「裏モード」）
//
// ★なんのためか
//   運営者（先生）が、ぜんぶの機能を 一気に 確かめるため。
//   ふだんの遊びでは 1日15分・1日12個・単元は じゅんに ひらく、という
//   しばりが あるので、確かめるのに 何日も かかってしまう。
//
// ★子どもが 入れないようにする
//   ・この印は `sg:teacher` に しまう（子どもの きろくとは べつ）
//   ・入り口は せんせいモードの 中だけ（タイトル3秒ながおし＋あんしょうばんごう）
//   ・入っている間は、画面の上に いつも 帯が 出る（切りわすれを ふせぐ）
//   ・この印が ついている間の あそびは、ふだんの きろくと 同じ場所に のこる。
//     確かめたあとは「きろくを まっさらにする」で 消せる。
import { state, saveTeacher } from "./store.js";

export function isDebug() {
  return state.teacher?.debug === true;
}

export function setDebug(on) {
  state.teacher.debug = !!on;
  saveTeacher();
}
